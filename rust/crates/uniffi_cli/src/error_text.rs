//! Generates one accessor per platform for the user-facing text of every UniFFI error
//!
//! UniFFI's Kotlin `message` on a structured error is a field dump such as `v1=...`, and its Swift
//! errors define the Rust `Display` text as `description` without declaring
//! `CustomStringConvertible`, so `localizedDescription` falls back to a type dump such as
//! `CoveCore.AuthManagerError.DecoySet(...)`. The files written here route both platforms to the
//! Rust text instead. Flat errors carry that text as their `message`, and every other error must
//! export `Display`, which is checked here so a new error cannot reach the UI as a type dump

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

const SWIFT_FILE_NAME: &str = "uniffi_error_text.swift";
const KOTLIN_FILE_NAME: &str = "uniffi_error_text.kt";
const DISPLAY_CALL: &str = "_uniffi_trait_display(";

// method bodies inside a generated error close with a `}` at column 0, so a type's block is read
// up to the FFI converter that UniFFI emits right after every error type instead
const SWIFT_BLOCK_END: &str = "public struct FfiConverterType";
const KOTLIN_BLOCK_END: &str = "public object FfiConverterType";
/// The first line UniFFI writes in each generated file, so sources around the output directory,
/// such as app code when it is the Android source root, are not read as bindings
const UNIFFI_MARKER: &str =
    "// This file was autogenerated by some hot garbage in the `uniffi` crate.";

const HEADER: &str =
    "// This file was generated by uniffi_cli from the UniFFI error types; do not edit";

#[derive(Debug, PartialEq, Eq)]
enum ErrorText {
    /// The error exports Rust `Display`
    Display,

    /// A flat error, whose variants each carry their Rust `Display` text as `message`
    Flat { variants: Vec<String> },
}

#[derive(Debug, PartialEq, Eq)]
struct UniffiError {
    name: String,
    text: ErrorText,
}

/// A structured error that cannot produce readable text
#[derive(Debug, PartialEq, Eq)]
struct MissingDisplay(String);

#[derive(Debug)]
pub enum Error {
    Io(PathBuf, io::Error),
    MissingDisplay(Vec<String>),
    NoErrorsFound(PathBuf),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io(path, error) => write!(f, "{}: {error}", path.display()),
            Self::MissingDisplay(names) => write!(
                f,
                "UniFFI errors without an exported Display: {}\nThe apps can only show these as a type dump; add #[uniffi::export(Display)] to each",
                names.join(", ")
            ),
            Self::NoErrorsFound(dir) => write!(
                f,
                "found no UniFFI error types in {}; the generated binding format may have changed",
                dir.display()
            ),
        }
    }
}

/// Writes a Swift file that makes every UniFFI error `CustomStringConvertible` with its Rust text
pub fn write_swift(out_dir: &Path) -> Result<(), Error> {
    let mut sources = Vec::new();
    for path in source_files(out_dir, "swift", false)? {
        let source = read(&path)?;
        if source.starts_with(UNIFFI_MARKER) {
            sources.push(source);
        }
    }

    let errors = collect(out_dir, sources.iter().flat_map(|source| scan_swift(source)))?;
    write(&out_dir.join(SWIFT_FILE_NAME), &render_swift(&errors))
}

/// Writes a Kotlin `Throwable.uniffiErrorText()` that returns the Rust text of any UniFFI error
pub fn write_kotlin(out_dir: &Path) -> Result<(), Error> {
    let mut scans = Vec::new();
    let mut root: Option<(String, PathBuf)> = None;

    for path in source_files(out_dir, "kt", true)? {
        let source = read(&path)?;
        if !source.starts_with(UNIFFI_MARKER) {
            continue;
        }

        let Some(package) = kotlin_package(&source) else { continue };

        // the shortest package is the root one that the other crates' packages nest under
        if root.as_ref().is_none_or(|(root, _)| package.len() < root.len()) {
            let dir = path.parent().unwrap_or(out_dir).to_path_buf();
            root = Some((package.clone(), dir));
        }

        scans.extend(scan_kotlin(&source, &package));
    }

    let Some((package, dir)) = root else { return Err(Error::NoErrorsFound(out_dir.into())) };
    let errors = collect(out_dir, scans)?;
    write(&dir.join(KOTLIN_FILE_NAME), &render_kotlin(&package, &errors))
}

/// Sorts the scanned errors, failing if any cannot produce readable text
fn collect(
    out_dir: &Path,
    scans: impl IntoIterator<Item = Result<UniffiError, MissingDisplay>>,
) -> Result<Vec<UniffiError>, Error> {
    let mut errors = Vec::new();
    let mut missing = Vec::new();
    for scan in scans {
        match scan {
            Ok(error) => errors.push(error),
            Err(MissingDisplay(name)) => missing.push(name),
        }
    }

    if !missing.is_empty() {
        missing.sort();
        return Err(Error::MissingDisplay(missing));
    }

    if errors.is_empty() {
        return Err(Error::NoErrorsFound(out_dir.into()));
    }

    errors.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(errors)
}

/// Finds the error enums in one generated Swift file
fn scan_swift(source: &str) -> Vec<Result<UniffiError, MissingDisplay>> {
    let mut lines = source.lines();
    let mut found = Vec::new();

    while let Some(line) = lines.next() {
        let Some(name) =
            line.strip_prefix("enum ").and_then(|rest| rest.split_once(": Swift.Error"))
        else {
            continue;
        };

        let mut variants = Vec::new();
        let mut has_display = false;
        for line in lines.by_ref().take_while(|line| !line.starts_with(SWIFT_BLOCK_END)) {
            has_display |= line.contains(DISPLAY_CALL);

            let variant = line.trim_start().strip_prefix("case ");
            if let Some(variant) = variant.and_then(|rest| rest.strip_suffix("(message: String)")) {
                variants.push(variant.to_string());
            }
        }

        found.push(classify(name.0.to_string(), has_display, variants));
    }

    found
}

/// Finds the error classes in one generated Kotlin file
fn scan_kotlin(source: &str, package: &str) -> Vec<Result<UniffiError, MissingDisplay>> {
    let mut lines = source.lines();
    let mut found = Vec::new();

    while let Some(line) = lines.next() {
        let Some(declaration) = line.strip_prefix("sealed class ") else { continue };
        let Some((name, _)) = declaration.split_once(": kotlin.Exception") else { continue };

        // a flat error passes its Rust text to the exception as the message
        let (name, is_flat) = match name.strip_suffix("(message: String)") {
            Some(name) => (name, true),
            None => (name, false),
        };

        let mut has_display = false;
        for line in lines.by_ref().take_while(|line| !line.starts_with(KOTLIN_BLOCK_END)) {
            has_display |= line.contains(DISPLAY_CALL);
        }

        // Kotlin reads a flat error's message without matching on its variants
        let variants = if is_flat { vec![String::new()] } else { Vec::new() };
        found.push(classify(format!("{package}.{name}"), has_display, variants));
    }

    found
}

fn classify(
    name: String,
    has_display: bool,
    flat_variants: Vec<String>,
) -> Result<UniffiError, MissingDisplay> {
    // a flat error cannot export Display, since UniFFI cannot lift it back into Rust
    let text = match (has_display, flat_variants.is_empty()) {
        (true, _) => ErrorText::Display,
        (false, false) => ErrorText::Flat { variants: flat_variants },
        (false, true) => return Err(MissingDisplay(name)),
    };

    Ok(UniffiError { name, text })
}

fn render_swift(errors: &[UniffiError]) -> String {
    let mut out = format!(
        "{HEADER}\n\n\
         // UniFFI errors define their Rust text as `description` without declaring\n\
         // `CustomStringConvertible`, so `localizedDescription` would show a type dump instead\n"
    );

    for error in errors {
        let name = &error.name;
        out.push('\n');

        match &error.text {
            ErrorText::Display => {
                out.push_str(&format!("extension {name}: CustomStringConvertible {{}}\n"))
            }
            ErrorText::Flat { variants } => {
                let cases = variants
                    .iter()
                    .map(|variant| format!("let .{variant}(message)"))
                    .collect::<Vec<_>>()
                    .join(",\n             ");

                out.push_str(&format!(
                    "extension {name}: CustomStringConvertible {{\n    \
                         public var description: String {{\n        \
                             switch self {{\n        \
                             case {cases}:\n            \
                                 return message\n        \
                             }}\n    \
                         }}\n\
                     }}\n"
                ));
            }
        }
    }

    out
}

fn render_kotlin(package: &str, errors: &[UniffiError]) -> String {
    let branches = errors
        .iter()
        .map(|error| {
            let text = match error.text {
                ErrorText::Display => "toString()",
                ErrorText::Flat { .. } => "message",
            };

            format!("        is {} -> {text}\n", error.name)
        })
        .collect::<String>();

    format!(
        "{HEADER}\n\n\
         package {package}\n\n\
         /**\n \
          * The Rust `Display` text of a UniFFI error, or null when this is not a UniFFI error\n \
          *\n \
          * Kotlin's `message` on a structured UniFFI error is a field dump such as `v1=...`, so read\n \
          * error text meant for people through this instead\n \
          */\n\
         fun Throwable.uniffiErrorText(): String? =\n    \
             when (this) {{\n\
         {branches}        \
                 else -> null\n    \
             }}\n"
    )
}

fn kotlin_package(source: &str) -> Option<String> {
    source
        .lines()
        .find_map(|line| line.strip_prefix("package "))
        .map(|package| package.trim().to_string())
}

/// Lists the generated sources in `dir`, sorted so the output does not depend on directory order
fn source_files(dir: &Path, extension: &str, recursive: bool) -> Result<Vec<PathBuf>, Error> {
    let entries = fs::read_dir(dir).map_err(|error| Error::Io(dir.into(), error))?;
    let mut files = Vec::new();

    for entry in entries {
        let path = entry.map_err(|error| Error::Io(dir.into(), error))?.path();
        if path.is_dir() && recursive {
            files.extend(source_files(&path, extension, true)?);
            continue;
        }

        let is_own_output = path
            .file_name()
            .is_some_and(|name| name == SWIFT_FILE_NAME || name == KOTLIN_FILE_NAME);

        if path.extension().is_some_and(|ext| ext == extension) && !is_own_output {
            files.push(path);
        }
    }

    files.sort();
    Ok(files)
}

fn read(path: &Path) -> Result<String, Error> {
    fs::read_to_string(path).map_err(|error| Error::Io(path.into(), error))
}

fn write(path: &Path, contents: &str) -> Result<(), Error> {
    fs::write(path, contents).map_err(|error| Error::Io(path.into(), error))
}

